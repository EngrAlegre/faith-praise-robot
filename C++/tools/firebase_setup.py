"""
One-time Firebase setup for the C++ Lab.

Does three things, and is safe to re-run:
  1. reads the web app config from the Firebase CLI and writes web/firebase-config.js
  2. turns on the Email/Password sign-in provider
  3. makes sure a Firestore database exists in asia-southeast1

It never prints the API key or the access token.

    python tools/firebase_setup.py
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

PROJECT = "cpp-lab-faith-praise"
ROOT = Path(__file__).resolve().parent.parent
CONFIGSTORE = Path(os.path.expanduser("~/.config/configstore/firebase-tools.json"))


def cli(*args: str) -> subprocess.CompletedProcess:
    cmd = "firebase " + " ".join(args)
    return subprocess.run(cmd, capture_output=True, text=True, cwd=str(ROOT), shell=True)


def access_token() -> str:
    data = json.loads(CONFIGSTORE.read_text(encoding="utf-8"))
    tokens = data.get("tokens", {})
    token = tokens.get("access_token")
    if not token:
        sys.exit("Not signed in: run `firebase login` first.")
    return token


def api(method: str, url: str, body: dict | None = None) -> tuple[int, dict]:
    headers = {"Authorization": f"Bearer {access_token()}",
               "Content-Type": "application/json",
               "x-goog-user-project": PROJECT}
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            raw = r.read().decode() or "{}"
            return r.status, json.loads(raw)
    except urllib.error.HTTPError as e:
        raw = e.read().decode() or "{}"
        try:
            return e.code, json.loads(raw)
        except json.JSONDecodeError:
            return e.code, {"raw": raw}


def write_config() -> dict:
    out = cli("apps:sdkconfig", "web", "--project", PROJECT).stdout
    start, end = out.find("{"), out.rfind("}")
    if start < 0 or end < 0:
        sys.exit("Could not read the web app config. Create the app first:\n"
                 f"  firebase apps:create web \"CPP Lab Web\" --project {PROJECT}")
    cfg = json.loads(out[start:end + 1])

    js = (
        "// Generated by tools/firebase_setup.py - safe to commit.\n"
        "// The API key identifies the project; it does not grant access.\n"
        "// Who can read or write what is enforced by firestore.rules.\n"
        "export const firebaseConfig = {\n"
        + "".join(f"  {k}: {json.dumps(v)},\n" for k, v in cfg.items())
        + "};\n"
    )
    (ROOT / "web" / "firebase-config.js").write_text(js, encoding="utf-8")
    print(f"  web/firebase-config.js written (project {cfg['projectId']}, app {cfg['appId'][-12:]})")
    return cfg


def enable_api(name: str) -> None:
    """Turn on a Google API for this project (idempotent)."""
    url = f"https://serviceusage.googleapis.com/v1/projects/{PROJECT}/services/{name}:enable"
    status, body = api("POST", url, {})
    if status == 200 and body.get("done"):
        print(f"  api {name}: ready")
        return
    if status == 200 and body.get("name"):
        # long-running operation: poll until done
        import time
        op = body["name"]
        for _ in range(30):
            st, opb = api("GET", f"https://serviceusage.googleapis.com/v1/{op}")
            if opb.get("done"):
                print(f"  api {name}: enabled")
                return
            time.sleep(2)
        print(f"  api {name}: still enabling, retry in a minute")
        return
    if status == 409 or "already enabled" in json.dumps(body).lower():
        print(f"  api {name}: already enabled")
        return
    print(f"  api {name}: FAILED ({status}) {json.dumps(body)[:200]}")


def initialize_auth() -> None:
    """A brand-new project has no identity platform config until this is called."""
    url = f"https://identitytoolkit.googleapis.com/v2/projects/{PROJECT}/identityPlatform:initializeAuth"
    status, body = api("POST", url, {})
    if status == 200:
        print("  identity platform: initialised")
    elif status == 400 and "already" in json.dumps(body).lower():
        print("  identity platform: already initialised")
    else:
        print(f"  identity platform: {status} {json.dumps(body)[:160]}")


def enable_email_password() -> None:
    base = f"https://identitytoolkit.googleapis.com/v2/projects/{PROJECT}/config"
    # PATCH creates the config on a fresh project, so no read first
    mask = "updateMask=signIn.email.enabled,signIn.email.passwordRequired"
    status, body = api("PATCH", f"{base}?{mask}",
                       {"signIn": {"email": {"enabled": True, "passwordRequired": True}}})
    if status == 200 and body.get("signIn", {}).get("email", {}).get("enabled"):
        print("  email/password sign-in: enabled")
    else:
        print(f"  email/password sign-in: FAILED ({status}) {json.dumps(body)[:200]}")


def ensure_firestore() -> None:
    listing = cli("firestore:databases:list", "--project", PROJECT)
    text = (listing.stdout or "") + (listing.stderr or "")
    if "(default)" in text:
        print("  firestore database: exists")
        return
    created = cli("firestore:databases:create", "default", "--project", PROJECT,
                  "--location", "asia-southeast1")
    ok = "created" in ((created.stdout or "") + (created.stderr or "")).lower()
    print(f"  firestore database: {'created in asia-southeast1' if ok else 'could not create - check the log'}")
    if not ok:
        print((created.stdout or "")[-400:])


def main() -> int:
    print(f"Firebase project: {PROJECT}")
    write_config()
    enable_api("identitytoolkit.googleapis.com")
    enable_api("firestore.googleapis.com")
    initialize_auth()
    enable_email_password()
    ensure_firestore()
    return 0


if __name__ == "__main__":
    sys.exit(main())
